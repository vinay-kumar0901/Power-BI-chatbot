def ask_ollama(prompt, system='You are a precise BI assistant.', timeout=None, max_tokens=384):
    """Call Ollama with bounded generation and a Colab-friendly long read timeout."""
    request_timeout = timeout or OLLAMA_REQUEST_TIMEOUT
    payload={
        'model':OLLAMA_MODEL,
        'stream':False,
        'keep_alive':'30m',
        'messages':[{'role':'system','content':system},{'role':'user','content':prompt}],
        'options':{'temperature':0.1,'num_predict':max_tokens,'num_ctx':3072,'num_batch':128,'num_thread':OLLAMA_NUM_THREADS}
    }
    r=requests.post(
        f'{OLLAMA_URL}/api/chat', json=payload,
        timeout=(OLLAMA_CONNECT_TIMEOUT, request_timeout)
    )
    r.raise_for_status()
    content=r.json().get('message',{}).get('content','').strip()
    if not content:
        raise RuntimeError('Ollama returned an empty response. Check that the configured model is available.')
    return content

def _schema_columns(schema):
    """Parse the compact schema text generated by datasets.schema_for."""
    found = {}
    for line in schema.splitlines():
        match = re.match(r'^TABLE\s+(.+?)\s*:\s*(.*)$', line.strip(), re.I)
        if not match:
            continue
        table = match.group(1).strip().strip('"')
        columns = set()
        for item in match.group(2).split(','):
            name = item.strip().split()[0] if item.strip() else ''
            if name:
                columns.add(name.lower())
        found[table.lower()] = columns
    return found


def _has_columns(schema_map, table, required):
    return table.lower() in schema_map and all(c.lower() in schema_map[table.lower()] for c in required)


def _net_sales_sql(question, schema):
    """Translate the supplied PBIP [Net Sales] DAX measure to safe SQLite SQL.

    DAX definition:
      [Net Sales] = [Sales After Line Discount] - [Order Discount Amount]
    Both component measures filter Orders to Completed and Shipped.
    The equivalent row expression is Qty * UnitPrice * (1-LineDiscount) * (1-DiscountRate).
    """
    q = question.lower()
    if not re.search(r'\bnet\s*sales\b', q):
        return None
    tables = _schema_columns(schema)
    od_cols = ['OrderID', 'ProductID', 'Quantity', 'UnitPrice', 'LineDiscount']
    order_cols = ['OrderID', 'OrderStatus', 'DiscountRate']
    if not (_has_columns(tables, 'OrderDetails', od_cols) and _has_columns(tables, 'Orders', order_cols)):
        return ('', 'The imported data does not contain all columns required by the PBIP Net Sales measure: OrderDetails(OrderID, ProductID, Quantity, UnitPrice, LineDiscount) and Orders(OrderID, OrderStatus, DiscountRate).')

    value_expr = (
        'od.Quantity * od.UnitPrice * '
        '(1 - COALESCE(od.LineDiscount, 0)) * '
        '(1 - COALESCE(o.DiscountRate, 0))'
    )
    where = "o.OrderStatus IN ('Completed', 'Shipped')"
    by_category = bool(re.search(r'\b(by|per|each|across)\s+categor(?:y|ies)\b|\bcategor(?:y|ies)[- ]wise\b', q))
    if by_category:
        if not _has_columns(tables, 'Products', ['ProductID', 'Category']):
            return ('', 'Net Sales can be calculated, but category grouping is unavailable because Products(ProductID, Category) was not imported.')
        sql = (
            'SELECT p.Category AS Category, '
            f'ROUND(SUM({value_expr}), 2) AS NetSales '
            'FROM OrderDetails AS od '
            'INNER JOIN Orders AS o ON o.OrderID = od.OrderID '
            'INNER JOIN Products AS p ON p.ProductID = od.ProductID '
            f'WHERE {where} '
            'GROUP BY p.Category '
            'ORDER BY NetSales DESC LIMIT 200'
        )
        return sql, 'Calculated from the PBIP Net Sales DAX measure and grouped by Products[Category]. Only Completed and Shipped orders are included.'

    sql = (
        f'SELECT ROUND(SUM({value_expr}), 2) AS NetSales '
        'FROM OrderDetails AS od '
        'INNER JOIN Orders AS o ON o.OrderID = od.OrderID '
        f'WHERE {where}'
    )
    return sql, 'Calculated from the PBIP Net Sales DAX measure. Only Completed and Shipped orders are included.'


def propose_sql(question, schema, context, history):
    q = question.lower()
    net_sales = _net_sales_sql(question, schema)
    if net_sales is not None:
        return net_sales

    # Pre-aggregated workbook summaries must be queried directly, never joined to facts.
    channel_schema = bool(re.search(r'TABLE\s+Channel\s*:', schema, re.I) and re.search(r'TABLE\s+Channel\s*:.*?\bSales\b', schema, re.I | re.S))
    if channel_schema and re.search(r'\b(sales|revenue)\b', q):
        if re.search(r'\b(by|per|each)\s+channel\b|\bchannel\s+wise\b', q):
            return 'SELECT Channel, Sales FROM Channel ORDER BY Sales DESC LIMIT 200', 'Used the pre-aggregated Channel summary table; no join is required.'
        if re.search(r'\b(total|overall|sum|all)\b', q):
            return 'SELECT SUM(Sales) AS TotalSales FROM Channel', 'Summed the Sales values in the pre-aggregated Channel summary table.'

    prompt=f"""Create ONE SQLite SELECT query to answer the user's data question.
Return JSON only: {{"sql":"SELECT ...","reason":"..."}}.
STRICT RULES:
- Use ONLY exact tables and columns listed in SCHEMA.
- Never invent a table, column, alias, or relationship.
- Do not join pre-aggregated summary tables to fact tables.
- A table named Channel with columns Channel, Sales, Orders is already a channel summary. Query it directly.
- Use exact SQLite table names; quote names with spaces using double quotes.
- If the requested metric is absent, return {{"sql":"","reason":"Required metric or columns are absent."}}.
- For Net Sales, follow the retrieved PBIP DAX definition. Never substitute gross Sales or a pre-aggregated Sales column.
- Add LIMIT 200 to detail queries; aggregate queries do not need LIMIT.
SCHEMA:\n{schema}\nPOWER BI CONTEXT:\n{context[:5000]}\nRECENT CONVERSATION:\n{history[-2500:]}\nQUESTION: {question}\nJSON:"""
    raw=ask_ollama(prompt,'You generate valid, safe, schema-grounded SQLite SELECT statements. Return JSON only.',timeout=min(OLLAMA_REQUEST_TIMEOUT,300),max_tokens=220)
    match=re.search(r'\{.*\}',raw,re.S)
    if not match: return '', 'The model did not return valid SQL JSON.'
    try:
        obj=json.loads(match.group()); return obj.get('sql','').strip(),obj.get('reason','')
    except Exception: return '', 'Could not parse the SQL proposal.'

def validate_sql(sql, db:Path):
    if not sql: raise ValueError('No SQL query was proposed.')
    if ';' in sql.rstrip(';'): raise ValueError('Only one SQL statement is allowed.')
    tree=sqlglot.parse_one(sql,read='sqlite')
    if not isinstance(tree, (exp.Select, exp.Union, exp.Intersect, exp.Except)): raise ValueError('Only SELECT statements are allowed.')
    if any(isinstance(x,(exp.Insert,exp.Update,exp.Delete,exp.Create,exp.Drop,exp.Alter,exp.Command)) for x in tree.walk()): raise ValueError('Unsafe SQL operation detected.')
    if re.search(r'\b(attach|detach|pragma|load_extension|readfile|writefile)\b',sql,re.I): raise ValueError('Blocked SQL keyword or function.')
    # Verify referenced tables exist in the selected dashboard database.
    if not db.exists(): raise ValueError('No data database exists for this dashboard. Upload CSV/XLSX exports first.')
    with sqlite3.connect(f'file:{db.as_posix()}?mode=ro',uri=True) as c:
        actual={r[0].lower() for r in c.execute("SELECT name FROM sqlite_master WHERE type='table'")}
    referenced={t.name.lower() for t in tree.find_all(exp.Table)}
    unknown=referenced-actual
    if unknown: raise ValueError('Unknown table(s): '+', '.join(sorted(unknown)))
    # SQLite prepares the statement without executing it, catching unknown columns and bad joins.
    with sqlite3.connect(f'file:{db.as_posix()}?mode=ro',uri=True) as c:
        c.execute('EXPLAIN QUERY PLAN ' + sql)
    return sql

def execute_readonly(sql, db:Path):
    sql=validate_sql(sql,db)
    with sqlite3.connect(f'file:{db.as_posix()}?mode=ro',uri=True) as c:
        c.row_factory=sqlite3.Row
        def authorizer(action,arg1,arg2,dbname,source):
            deny={sqlite3.SQLITE_INSERT,sqlite3.SQLITE_UPDATE,sqlite3.SQLITE_DELETE,sqlite3.SQLITE_ALTER_TABLE,sqlite3.SQLITE_DROP_TABLE,sqlite3.SQLITE_DROP_INDEX,sqlite3.SQLITE_CREATE_TABLE,sqlite3.SQLITE_ATTACH,sqlite3.SQLITE_DETACH}
            return sqlite3.SQLITE_DENY if action in deny else sqlite3.SQLITE_OK
        c.set_authorizer(authorizer)
        cur=c.execute(sql); cols=[x[0] for x in cur.description or []]
        rows=[dict(x) for x in cur.fetchmany(200)]
    return {'columns':cols,'rows':rows,'row_count':len(rows)}
